"""Content-address every asset and verify storyboards only use locked, published assets.

    python3 video-style/tools/asset_lock.py                 # validate manifests, (re)write assets.lock.json
    python3 video-style/tools/asset_lock.py --check         # fail if any file changed since the lock
    python3 video-style/tools/asset_lock.py --check sb.yaml # also verify every id@version the storyboard uses

The lockfile is the deterministic contract between the asset library and the
renderer: a storyboard renders identically for as long as the lock's hashes match.
"""
import hashlib
import json
import pathlib
import re
import sys

import jsonschema
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
LOCK = ROOT / "assets.lock.json"
SCHEMA = json.loads((ROOT / "schemas" / "asset.schema.json").read_text())
REF = re.compile(r"\b([a-z]+\.[a-z0-9-]+)@(\d+\.\d+\.\d+)\b")


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def resolve(manifest_dir, rel):
    return ROOT / rel[1:] if rel.startswith("/") else manifest_dir / rel


def scan():
    entries, errors = {}, []
    for mf in sorted(ASSETS.rglob("asset.json")):
        m = json.loads(mf.read_text())
        try:
            jsonschema.validate(m, SCHEMA)
        except jsonschema.ValidationError as e:
            errors.append(f"{mf.relative_to(ROOT)}: {e.message}")
            continue
        key = f"{m['id']}@{m['version']}"
        if key in entries:
            errors.append(f"duplicate asset {key}")
        files = {}
        for f in m["files"]:
            p = resolve(mf.parent, f["path"])
            if not p.exists():
                errors.append(f"{key}: missing file {f['path']}")
                continue
            files[str(p.relative_to(ROOT))] = sha256(p)
        entries[key] = {
            "manifest": str(mf.relative_to(ROOT)),
            "manifest_sha256": sha256(mf),
            "status": m["status"],
            "kind": m["kind"],
            "files": files,
        }
    return entries, errors


def main(argv):
    check = "--check" in argv
    boards = [a for a in argv if not a.startswith("--")]
    entries, errors = scan()
    if errors:
        print("manifest errors:\n  " + "\n  ".join(errors))
        return 1
    lock = {"$comment": "Generated by tools/asset_lock.py. Do not edit by hand.", "assets": entries}
    if not check:
        LOCK.write_text(json.dumps(lock, indent=1, sort_keys=True) + "\n")
        print(f"wrote {LOCK.relative_to(ROOT.parent)} ({len(entries)} assets)")
        return 0

    if not LOCK.exists():
        print("no assets.lock.json; run without --check first")
        return 1
    locked = json.loads(LOCK.read_text())["assets"]
    problems = []
    for key, e in entries.items():
        if key not in locked:
            problems.append(f"{key}: not in lock (new asset? re-run asset_lock.py)")
        elif locked[key] != e:
            problems.append(f"{key}: content changed since lock. Bump the version instead of editing a published asset")
    for key in locked.keys() - entries.keys():
        problems.append(f"{key}: in lock but manifest is gone")
    for b in boards:
        text = pathlib.Path(b).read_text()
        yaml.safe_load(text)  # must parse
        for aid, ver in sorted(set(REF.findall(text))):
            key = f"{aid}@{ver}"
            if key not in locked:
                problems.append(f"{b}: references unknown asset {key}")
            elif locked[key]["status"] != "published":
                problems.append(f"{b}: {key} is '{locked[key]['status']}', only 'published' assets may be locked into a storyboard")
    if problems:
        print("lock check FAILED:\n  " + "\n  ".join(problems))
        return 1
    print(f"lock OK ({len(entries)} assets" + (f", {len(boards)} storyboard(s) resolved)" if boards else ")"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
